import 'server-only';
import { createHash } from 'node:crypto';
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import { strToU8, zipSync } from 'fflate';

export type ReportTable = { title: string; columns: string[]; rows: (string | number | null | undefined)[][] };
export type ReportProvenance = { company: string; project: string; report: string; generatedISO: string; exportId: string; generatedBy: string; sourceHash: string };

export function reportHash(table: ReportTable): string {
  return createHash('sha256').update(JSON.stringify([table.columns, table.rows])).digest('hex');
}
const xml = (value: unknown) => String(value ?? '').replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&apos;');
const col = (index: number): string => { let value = index + 1, name = ''; while (value > 0) { value--; name = String.fromCharCode(65 + value % 26) + name; value = Math.floor(value / 26); } return name; };
function sheet(rows: (string | number | null | undefined)[][]): string {
  const body = rows.map((row, index) => `<row r="${index + 1}">${row.map((cell, column) => `<c r="${col(column)}${index + 1}" t="inlineStr"><is><t>${xml(cell)}</t></is></c>`).join('')}</row>`).join('');
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>${body}</sheetData></worksheet>`;
}

/** Minimal, standards-compliant XLSX: an audit cover sheet plus the complete scoped table. */
export function reportSpreadsheet(table: ReportTable, meta: ReportProvenance): Uint8Array {
  const cover: string[][] = [
    ['Propbrew construction export', table.title], ['Company', meta.company], ['Project', meta.project],
    ['Report', meta.report], ['Generated (UTC)', meta.generatedISO], ['Generated by', meta.generatedBy],
    ['Export ID', meta.exportId], ['Source SHA-256', meta.sourceHash], ['Data rows', String(table.rows.length)],
  ];
  const files: Record<string, Uint8Array> = {
    '[Content_Types].xml': strToU8('<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/><Override PartName="/xl/worksheets/sheet2.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/></Types>'),
    '_rels/.rels': strToU8('<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>'),
    'xl/workbook.xml': strToU8('<?xml version="1.0" encoding="UTF-8"?><workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="Export details" sheetId="1" r:id="rId1"/><sheet name="Records" sheetId="2" r:id="rId2"/></sheets></workbook>'),
    'xl/_rels/workbook.xml.rels': strToU8('<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/><Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet2.xml"/></Relationships>'),
    'xl/worksheets/sheet1.xml': strToU8(sheet(cover)),
    'xl/worksheets/sheet2.xml': strToU8(sheet([table.columns, ...table.rows])),
  };
  return zipSync(files, { level: 6 });
}

/** Every PDF page repeats provenance so a detached page remains traceable. */
export async function reportPdf(table: ReportTable, meta: ReportProvenance): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  doc.setTitle(`${meta.project} | ${table.title}`); doc.setAuthor('Propbrew'); doc.setSubject(`Export ${meta.exportId}; source ${meta.sourceHash}`);
  const safe = (value: unknown) => String(value ?? '').normalize('NFKD').replace(/[^\x20-\x7e]/g, '?');
  const width = 595, height = 842, margin = 42;
  let page = doc.addPage([width, height]); let y = height - margin;
  const header = () => {
    page.drawText('PROPBREW  /  CONSTRUCTION', { x: margin, y, font: bold, size: 9, color: rgb(0.2, 0.25, 0.35) }); y -= 25;
    page.drawText(safe(table.title).slice(0, 80), { x: margin, y, font: bold, size: 17 }); y -= 23;
    page.drawText(safe(`${meta.company}  |  ${meta.project}`).slice(0, 95), { x: margin, y, font, size: 9 }); y -= 18;
    page.drawText(safe(`Generated ${meta.generatedISO} by ${meta.generatedBy}`).slice(0, 105), { x: margin, y, font, size: 8 }); y -= 22;
  };
  const footer = () => {
    page.drawText(`Export ${meta.exportId}  |  source SHA-256 ${meta.sourceHash}`, { x: margin, y: 27, font, size: 7 });
  };
  header();
  const lines = table.rows.length ? table.rows : [['No records in this project scope.']];
  for (let i = 0; i < lines.length; i++) {
    if (y < 86) { footer(); page = doc.addPage([width, height]); y = height - margin; header(); }
    const parts = table.columns.map((name, index) => `${name}: ${lines[i][index] ?? ''}`).join('   |   ');
    const text = safe(parts);
    for (let offset = 0; offset < text.length; offset += 115) {
      if (y < 86) { footer(); page = doc.addPage([width, height]); y = height - margin; header(); }
      page.drawText(text.slice(offset, offset + 115), { x: margin, y, font, size: 8, maxWidth: width - margin * 2 }); y -= 13;
    }
    y -= 6;
  }
  footer();
  return doc.save();
}
